/**
 * Grouping key for an `Epic:` value: trimmed, internal whitespace collapsed,
 * case-folded. `Marketplace`, `marketplace` and ` Marketplace ` are one epic —
 * cards are written by hand across sessions and the spelling drifts, so the raw
 * string is not an identity. The DISPLAY label is the first spelling seen in
 * scan order (readdir, filename-sorted — deterministic across machines), so the
 * page shows a real spelling from a real card rather than a folded token.
 */
function epicKeyOf(epic) {
  return epic.trim().replace(/\s+/g, " ").toLowerCase();
}

// key (normalized) -> { label (first-seen spelling), members }
const epicsMap = new Map();
for (const s of scanned) {
  const key = s.card.epic === null ? NO_EPIC : epicKeyOf(s.card.epic);
  if (!epicsMap.has(key)) {
    epicsMap.set(key, { label: s.card.epic ?? NO_EPIC, members: [] });
  }
  epicsMap.get(key).members.push(s);
}
// Alphabetical by normalized key, with the "(no epic)" bucket (pre-T49 cards) last.
const epicKeys = [...epicsMap.keys()].filter((k) => k !== NO_EPIC).sort();
if (epicsMap.has(NO_EPIC)) epicKeys.push(NO_EPIC);
// The "(no epic)" bucket is a bucket, not an epic: it is excluded from every
// epic COUNT (heading and stat chip alike) while still being rendered.
const epicCount = epicKeys.filter((k) => k !== NO_EPIC).length;

/**
 * Status of a scanned card as BOTH sources report it — its own `**Status:**`
 * header and its `plan/INDEX.md` row. Round 1 of PR #69: this used to prefer
 * the card and return one keyword, which is exactly the silent pick the Tasks
 * section refuses to make (see this file's header comment and the page footer).
 * `keyword` is null on a disagreement; callers must then show both.
 */
function scannedStatus(s) {
  const row = rowByFile.get(s.file);
  const index = row
    ? (statusKeyword(row.status) ?? normalizeStatus(row.status))
    : null;
  const card = s.card.status
    ? (statusKeyword(s.card.status) ?? normalizeStatus(s.card.status))
    : null;
  const mismatch = index !== null && card !== null && index !== card;
  const agreed = card ?? index;
  return {
    index,
    card,
    mismatch,
    keyword: mismatch
      ? null
      : agreed && KNOWN_STATUSES.includes(agreed)
        ? agreed
        : "unrecognised",
  };
}

/**
 * Per-status counts for one epic, plus a separate `mismatch` tally. A card whose
 * two sources disagree is counted ONLY as a mismatch — counting it under either
 * status would be the silent pick again, one aggregation level up.
 */
function epicStatusCounts(members) {
  const c = {};
  let mismatch = 0;
  for (const m of members) {
    const st = scannedStatus(m);
    if (st.mismatch) mismatch++;
    else c[st.keyword] = (c[st.keyword] ?? 0) + 1;
  }
  return { counts: c, mismatch };
}


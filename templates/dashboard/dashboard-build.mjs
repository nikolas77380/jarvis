/**
 * dashboard-build.mjs — render plan/INDEX.md + plan/T*.md into dashboard/index.html.
 *
 * Zero dependencies, no network. Node >= 20.
 *
 *   node scripts/dashboard-build.mjs
 *   node scripts/dashboard-build.mjs --lang <code> [--out <path>]
 *   node scripts/dashboard-build.mjs --plan-dir <path> --out <path>   (tests/fixtures)
 *
 * --plan-dir REQUIRES --out: without it the default output path is the tracked
 * dashboard/index.html, and a fixture run would overwrite it.
 *
 * Localization: the page CHROME (title, labels, status badge text, warnings)
 * comes from the DEFAULT_STRINGS table below — English, and English only, in
 * this file. `--lang <code>` merges dashboard/i18n/<code>.json (flat
 * key→string, local-only and gitignored — see dashboard/README.md) over the
 * defaults; missing keys fall back to English. Task ids, titles, notes and
 * Next lines are DATA from plan/*.md and are always rendered verbatim.
 * Localized output defaults to dashboard/index.<code>.html (also gitignored);
 * `--out` overrides the output path.
 *
 * Sources of truth:
 *   - plan/INDEX.md table rows (id, task, status, owner, depends on, note)
 *   - each card's parsed header (see plan/TEMPLATE.md):
 *       **Status:** … · **Owner:** … · **Depends on:** …
 *       PR: #18            (own line; "none yet" means no PR)
 *       **Epic:** …        (cross-session grouping key — T51's roll-up axis)
 *       **Next:** …        (may continue on following lines until a blank one)
 *
 * Where INDEX and a card disagree on status, the dashboard shows BOTH and marks
 * the section as inconsistent — it never silently picks one.
 *
 * The epic roll-up (T51) is built by scanning plan/*.md DIRECTLY — every card
 * file, under both id shapes (legacy T<nn>[<letter>] and session-scoped
 * <YYMMDD-HHMM>-<NNN>; they coexist permanently, see CLAUDE.md "Task ids") —
 * so the task-state summary is generated, never appended by hand per session.
 * Cards without an Epic: line (every pre-T49 card) land in an explicit
 * "(no epic)" bucket rather than being dropped. The roll-up key is NORMALIZED
 * (trim, collapse whitespace, case-fold) so hand-typed spelling drift across
 * sessions does not split one epic in two, and the "never silently picks one"
 * rule above holds for the roll-up as well: a member whose card and INDEX row
 * disagree is marked, counted apart, and shows both. This replaces per-session
 * task-STATUS appends only: OVERVIEW.md's hand-written narrative log (events
 * with no card — incidents, reversed decisions, measurements) is out of scope
 * and untouched by this script.
 */


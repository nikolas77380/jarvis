// ---------------------------------------------------------------- helpers

function esc(s) {
  return String(s)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

/** Escape first, then render a safe subset of inline markdown. */
function inlineMd(s) {
  let e = esc(s);
  e = e.replace(/`([^`]+)`/g, "<code>$1</code>");
  e = e.replace(/\*\*([^*]+(?:\*(?!\*)[^*]*)*)\*\*/g, "<strong>$1</strong>");
  e = e.replace(
    new RegExp(`\\[\\[(${TASK_ID_PATTERN})\\]\\]`, "g"),
    '<a href="#$1">$1</a>'
  );
  return e;
}

/** Escaped chrome string with {placeholder} values (escaped) filled in. */
function chrome(key, params = {}) {
  let out = esc(STRINGS[key]);
  for (const [name, value] of Object.entries(params)) {
    out = out.replaceAll(`{${name}}`, esc(value));
  }
  return out;
}

/** Strip bold markers and trim — for comparing statuses, not for display. */
function normalizeStatus(s) {
  return s.replaceAll("*", "").trim().toLowerCase();
}

/** Leading known-status keyword, or null. "done (cancelled …)" -> "done". */
function statusKeyword(s) {
  const n = normalizeStatus(s);
  for (const k of KNOWN_STATUSES) {
    if (n === k || n.startsWith(k + " ") || n.startsWith(k + ",")) return k;
  }
  return null;
}

/** Display text for a status: localized when the keyword is known, verbatim otherwise. */
function statusText(rawStatus, keyword) {
  if (keyword && KNOWN_STATUSES.includes(keyword)) {
    return STRINGS[`status.${keyword}`];
  }
  return normalizeStatus(rawStatus);
}

/** Split a markdown table row into cells, honouring backslash-escaped pipes. */
function splitRow(line) {
  const cells = [];
  let cur = "";
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === "\\" && line[i + 1] === "|") {
      cur += "|";
      i++;
    } else if (ch === "|") {
      cells.push(cur.trim());
      cur = "";
    } else {
      cur += ch;
    }
  }
  cells.push(cur.trim());
  // A well-formed row starts and ends with a pipe: drop the empty edges.
  if (cells.length && cells[0] === "") cells.shift();
  if (cells.length && cells[cells.length - 1] === "") cells.pop();
  return cells;
}

// ---------------------------------------------------------------- parse INDEX

function parseIndex(indexPath) {
  const lines = readFileSync(indexPath, "utf8").split("\n");
  const rows = [];
  for (const line of lines) {
    if (!line.trimStart().startsWith("|")) continue;
    const cells = splitRow(line.trim());
    if (cells.length < 6) continue;
    if (/^id$/i.test(cells[0])) continue; // header row
    if (/^:?-{2,}:?$/.test(cells[0].replaceAll(" ", ""))) continue; // separator
    const m = cells[0].match(/\[([^\]]+)\]\(([^)]+)\)/);
    rows.push({
      id: m ? m[1] : cells[0],
      cardFile: m ? m[2] : null,
      task: cells[1],
      status: cells[2],
      owner: cells[3],
      dependsOn: cells[4],
      note: cells[5],
    });
  }
  return rows;
}

// ---------------------------------------------------------------- parse card

function parseCard(cardPath) {
  if (!existsSync(cardPath)) return { missing: true };
  const lines = readFileSync(cardPath, "utf8").split("\n");
  const card = {
    missing: false,
    status: null,
    owner: null,
    pr: null,
    prRaw: null,
    epic: null,
    next: null,
  };

  // Header line: **Status:** … · **Owner:** … · **Depends on:** …
  // May wrap onto following lines until PR:/Next:/blank.
  const stIdx = lines.findIndex((l) => /^\*\*Status:\*\*/.test(l));
  if (stIdx !== -1) {
    let header = lines[stIdx];
    for (let i = stIdx + 1; i < lines.length; i++) {
      const l = lines[i];
      if (
        l.trim() === "" ||
        /^\*{0,2}PR\*{0,2}:/.test(l) ||
        /^\*\*Next:\*\*/.test(l)
      )
        break;
      header += " " + l.trim();
    }
    for (const seg of header.split(/\s+·\s+(?=\*\*)/)) {
      const m = seg.match(/^\*\*(.+?):\*\*\s*(.*)$/);
      if (!m) continue;
      const key = m[1].toLowerCase();
      if (key === "status") card.status = m[2].trim();
      if (key === "owner") card.owner = m[2].trim();
    }
  }

  // PR line: `PR: #18` (review-rounds.sh format) or `**PR:** <url>`; "none…" = no PR.
  const prLine = lines.find((l) => /^\*{0,2}PR\*{0,2}:/.test(l));
  if (prLine) {
    const value = prLine.replace(/^\*{0,2}PR\*{0,2}:\s*/, "").trim();
    card.prRaw = value;
    const num = value.match(/#(\d+)/) || value.match(/\/pull\/(\d+)/);
    if (num && !/^none\b/i.test(value)) card.pr = Number(num[1]);
  }

  // **Epic:** line (T49 template field, T51 roll-up axis). Wrapping backticks
  // are stripped for grouping; an unfilled template placeholder (<…>) or a
  // dash counts as absent — the card then lands in the "(no epic)" bucket.
  const epLine = lines.find((l) => /^\*\*Epic:\*\*/.test(l));
  if (epLine) {
    let v = epLine.replace(/^\*\*Epic:\*\*\s*/, "").trim();
    v = v.replace(/^`(.+)`$/s, "$1").trim();
    if (v && !/^<.*>$/s.test(v) && v !== "—" && v !== "-") card.epic = v;
  }

  // **Next:** line, continuing until the first blank line.
  const nxIdx = lines.findIndex((l) => /^\*\*Next:\*\*/.test(l));
  if (nxIdx !== -1) {
    const parts = [lines[nxIdx].replace(/^\*\*Next:\*\*\s*/, "").trim()];
    for (let i = nxIdx + 1; i < lines.length; i++) {
      if (lines[i].trim() === "") break;
      parts.push(lines[i].trim());
    }
    card.next = parts.join(" ").trim();
  }

  return card;
}


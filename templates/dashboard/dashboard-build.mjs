const epicSections = epicKeys
  .map((key) => {
    const { members } = epicsMap.get(key);
    const { counts: sc, mismatch } = epicStatusCounts(members);
    let countChips = [...KNOWN_STATUSES, "unrecognised"]
      .filter((k) => sc[k])
      .map((k) => {
        const known = KNOWN_STATUSES.includes(k);
        return `<span class="st ${known ? `st-${k}` : "st-other"}">${sc[k]} ${chrome(known ? `stat.${k}` : "stat.unrecognised")}</span>`;
      })
      .join("\n");
    if (mismatch) {
      countChips += `\n<span class="st st-mismatch">${mismatch} ${chrome("stat.mismatch")}</span>`;
    }
    const chips = members
      .map((m) => {
        const st = scannedStatus(m);
        // On a disagreement the chip carries BOTH statuses and a marker; it
        // never renders one of them as if it were the answer.
        const cls = st.mismatch
          ? "st-mismatch"
          : KNOWN_STATUSES.includes(st.keyword)
            ? `st-${st.keyword}`
            : "st-other";
        const title = st.mismatch
          ? `plan/${m.file} — ${STRINGS["stat.mismatch"]}: ${st.index} / ${st.card}`
          : `plan/${m.file} — ${st.keyword}`;
        const data = st.mismatch
          ? `data-status-index="${esc(st.index)}" data-status-card="${esc(st.card)}"`
          : `data-status="${esc(st.keyword)}"`;
        const text = st.mismatch ? `${m.id} ⚠` : m.id;
        // Only indexed cards have a task section to link to; a scanned-only
        // card renders as plain text plus the warning line below.
        return indexedFiles.has(m.file)
          ? `<a class="st ${cls}" href="#${esc(m.id)}" title="${esc(title)}" ${data}>${esc(text)}</a>`
          : `<span class="st ${cls}" title="${esc(title)}" ${data}>${esc(text)}</span>`;
      })
      .join("\n");
    const warns = members
      .flatMap((m) => {
        const out = [];
        if (!indexedFiles.has(m.file)) {
          out.push(
            `<div class="warnline">${chrome("warn.notIndexed", { file: `plan/${m.file}` })}</div>`
          );
        }
        const st = scannedStatus(m);
        if (st.mismatch) {
          out.push(
            `<div class="warnline"><code>plan/${esc(m.file)}</code> ${chrome("warn.mismatch", { index: st.index, card: st.card })}</div>`
          );
        }
        return out;
      })
      .join("\n");
    return `<div class="card${mismatch ? " mismatch" : ""}" id="${esc(epicAnchors.get(key))}">
<div class="row"><div class="t">${esc(epicName(key))}</div><span class="badge">${chrome("epic.cards", { n: String(members.length) })}</span></div>
<div class="ecounts">${countChips}</div>
<div class="emembers">${chips}</div>
${warns}
</div>`;
  })
  .join("\n");

const sections = tasks
  .map(({ row, card, idxKeyword, cardKeyword, inconsistent }) => {
    const badges = [statusBadge(row.status, idxKeyword)];
    if (inconsistent && card.status) {
      badges.push(
        statusBadge(card.status, cardKeyword, `${STRINGS["label.card"]}: `)
      );
    }
    const metaBits = [];
    metaBits.push(
      `<span><b>${chrome("label.owner")}:</b> ${ownerBadge(row.owner) || esc(normalizeStatus(row.owner) || "—")}</span>`
    );
    metaBits.push(
      `<span><b>${chrome("label.dependsOn")}:</b> ${inlineMd(row.dependsOn || "—")}</span>`
    );
    if (card.pr) {
      metaBits.push(
        `<span><b>${chrome("label.pr")}:</b> <a href="${PR_BASE}${card.pr}">#${card.pr}</a></span>`
      );
    } else {
      metaBits.push(
        `<span><b>${chrome("label.pr")}:</b> ${esc(card.prRaw || STRINGS["pr.none"])}</span>`
      );
    }
    if (row.cardFile) {
      metaBits.push(
        `<span><b>${chrome("label.card")}:</b> <code>plan/${esc(row.cardFile)}</code></span>`
      );
    }

    let warn = "";
    if (card.missing) {
      warn = `<div class="warnline">${chrome("warn.cardMissing", { file: row.cardFile ?? "(no file)" })}</div>`;
    } else if (!card.status) {
      warn = `<div class="warnline">${chrome("warn.noStatus")}</div>`;
    } else if (inconsistent) {
      warn = `<div class="warnline">${chrome("warn.mismatch", { index: normalizeStatus(row.status), card: normalizeStatus(card.status) })}</div>`;
    }

    const nextHtml = card.next
      ? `<div class="next"><b>${chrome("label.next")}:</b> ${inlineMd(card.next)}</div>`
      : `<div class="next"><b>${chrome("label.next")}:</b> <em>${chrome("next.none")}</em></div>`;

    return `<div class="card${inconsistent || card.missing ? " mismatch" : ""}" id="${esc(row.id)}">
<div class="row"><span class="tid">${esc(row.id)}</span><div class="t">${inlineMd(row.task)}</div>${badges.join("")}</div>
${warn}
<div class="meta">${metaBits.join("\n")}</div>
<div class="goal">${inlineMd(row.note)}</div>
${nextHtml}
</div>`;
  })
  .join("\n");


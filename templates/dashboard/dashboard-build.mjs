/**
 * Status badge. The visible text is localized; the canonical English status
 * word (the vocabulary plan/INDEX.md uses) always travels along in the
 * title/data-status attributes. `textPrefix` is prepended to the visible
 * text only (used for the "card: …" mismatch badge).
 */
function statusBadge(rawStatus, keyword, textPrefix = "") {
  const known = keyword && KNOWN_STATUSES.includes(keyword);
  const cls = known ? `st-${keyword}` : "st-other";
  const canonical = known ? keyword : normalizeStatus(rawStatus);
  const text = textPrefix + statusText(rawStatus, keyword);
  return `<span class="st ${cls}" title="${esc(canonical)}" data-status="${esc(canonical)}">${esc(text)}</span>`;
}

function ownerBadge(owner) {
  const o = normalizeStatus(owner);
  if (o === "" || o === "—" || o === "-") return "";
  let cls = "";
  if (o.startsWith("nextjs")) cls = " own-next";
  else if (o.startsWith("nestjs")) cls = " own-nest";
  else if (o.startsWith("general-purpose")) cls = " own-gp";
  return `<span class="badge${cls}">${esc(o)}</span>`;
}

/**
 * Anchor ids for the epic sections, assigned in one pass so they are unique BY
 * CONSTRUCTION. Normalizing the roll-up key already merges `Marketplace` and
 * `marketplace`, but two genuinely different epics can still slug alike
 * (`Marketplace UI` vs `marketplace-ui`), so a colliding slug takes a numeric
 * suffix in epicKeys order — deterministic, so the anchor of a given epic is
 * stable as long as the set of epics is. `epic-none` is reserved for the
 * "(no epic)" bucket before anything else can claim it.
 */
const epicAnchors = new Map();
{
  const used = new Set(["epic-none"]);
  for (const key of epicKeys) {
    if (key === NO_EPIC) {
      epicAnchors.set(key, "epic-none");
      continue;
    }
    const slug =
      key.replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "unnamed";
    let anchor = `epic-${slug}`;
    for (let n = 2; used.has(anchor); n++) anchor = `epic-${slug}-${n}`;
    used.add(anchor);
    epicAnchors.set(key, anchor);
  }
  // Cheap assertion rather than a trusted invariant: a duplicate DOM id makes
  // every nav link to the second section dead, and silently.
  if (new Set(epicAnchors.values()).size !== epicAnchors.size) {
    console.error("dashboard-build: epic anchor ids are not unique");
    process.exit(1);
  }
}

/** Epic display name (localized for the no-epic bucket, first-seen spelling otherwise). */
function epicName(key) {
  return key === NO_EPIC ? STRINGS["epic.none"] : epicsMap.get(key).label;
}

